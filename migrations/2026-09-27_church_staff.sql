-- 배경:
--   교회현황 화면에 교회별 목회자(담임목사/부목사/전도사) 명단을 보여주고,
--   인사이동으로 목사님이 바뀌면 자동으로 반영되도록 한다.
--   출처는 로그인 없이 볼 수 있는 공개 페이지
--   https://church.jbch.org/guide/organization.php?chId=<교회번호>
--   서버가 주 1회(매일 새벽 일부씩) 다시 읽어와 바뀐 점을 기록한다.
--
-- 실행 방법:
--   Supabase 대시보드 → SQL Editor → 아래 전체를 붙여넣고 Run
--   (IF NOT EXISTS를 써서 여러 번 실행해도 안전함. 기존 데이터는 건드리지 않음)
-- ============================================================

-- 1) 교회 테이블에 연동용 칸 추가
ALTER TABLE churches ADD COLUMN IF NOT EXISTS jbch_ch_id integer;         -- 교회 안내 사이트의 교회 번호(chId)
ALTER TABLE churches ADD COLUMN IF NOT EXISTS staff_synced_at timestamptz; -- 마지막으로 명단을 가져온 시각
ALTER TABLE churches ADD COLUMN IF NOT EXISTS staff_sync_error text;       -- 마지막 가져오기 실패 사유(성공 시 NULL)

-- 2) 교회별 현재 목회자 명단
CREATE TABLE IF NOT EXISTS church_staff (
  id bigserial PRIMARY KEY,
  church_id integer NOT NULL REFERENCES churches(id) ON DELETE CASCADE,
  jbch_person_id integer,          -- 교회 안내 사이트의 사람 고유번호 (이동 추적용)
  role text NOT NULL,              -- 담임목사 / 부목사 / 전도사 (사이트 구분 그대로)
  name text NOT NULL,              -- 이름 (예: 홍정현)
  title text,                      -- 호칭 (예: 목사, 전도사)
  duties text,                     -- 담당 (예: 수지(6)교구, 주차관리부)
  photo_url text,
  sort_order integer NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_church_staff_church ON church_staff (church_id, sort_order);

-- 3) 변경 이력 (부임/이임/직분 변경)
CREATE TABLE IF NOT EXISTS church_staff_changes (
  id bigserial PRIMARY KEY,
  church_id integer NOT NULL REFERENCES churches(id) ON DELETE CASCADE,
  change_type text NOT NULL,       -- added(부임) / removed(이임) / role_changed(직분 변경)
  jbch_person_id integer,
  name text NOT NULL,
  title text,
  old_role text,
  new_role text,
  detected_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_church_staff_changes_church ON church_staff_changes (church_id, detected_at DESC);

-- 4) 외부(웹 API) 직접 접근 차단 — 서버는 secret 키로 접근하므로 영향 없음
--    (Security Advisor "RLS Disabled in Public" 경고 예방)
ALTER TABLE church_staff ENABLE ROW LEVEL SECURITY;
ALTER TABLE church_staff_changes ENABLE ROW LEVEL SECURITY;

